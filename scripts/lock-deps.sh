#!/usr/bin/env bash
# lock-deps.sh - generate pinned dependency locks (backend/requirements.txt and
# frontend/package-lock.json) using throwaway Docker containers, so the host needs
# nothing but Docker. Run once on a machine that can reach PyPI and npm, then commit
# the two files. Re-run whenever backend/requirements.in or frontend/package.json change.
set -Eeuo pipefail
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

echo "==> backend/requirements.txt"
docker run --rm -v "${root}/backend:/w" -w /w python:3.12-slim bash -c '
  set -e
  python -m venv /tmp/v && /tmp/v/bin/pip install -q --upgrade pip
  /tmp/v/bin/pip install -q -r requirements.in
  { echo "# GENERATED by scripts/lock-deps.sh from requirements.in - do not edit."
    /tmp/v/bin/pip freeze --exclude-editable | grep -v -E "^(pip|setuptools|wheel)=="
  } > requirements.txt'

echo "==> frontend/package-lock.json"
docker run --rm -v "${root}/frontend:/w" -w /w node:22-alpine \
  npm install --package-lock-only --ignore-scripts

echo "done. Commit backend/requirements.txt and frontend/package-lock.json."
