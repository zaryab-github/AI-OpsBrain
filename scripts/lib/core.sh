# shellcheck shell=bash
# Core module lifecycle: install, status, upgrade, remove.

core_preflight() {
  check_docker
  have openssl || die "openssl is required (apt-get install openssl)"
  if [[ -r /etc/os-release ]]; then
    # shellcheck disable=SC1091
    . /etc/os-release
    case "${ID:-}" in
      ubuntu | debian) ;;
      *) warn "Tested on Ubuntu 24.04 and Debian 12; this is ${PRETTY_NAME:-unknown}." ;;
    esac
  fi
  local mem_kb
  mem_kb=$(awk '/MemTotal/ {print $2}' /proc/meminfo 2>/dev/null || echo 0)
  ((mem_kb >= 3500000)) || warn "Less than 4 GB RAM; the core module needs about 2 GB, Logging and Monitoring more."
}

core_write_config() {
  install -d -m 0755 "$OPSBRAIN_ETC" "$OPSBRAIN_ETC/state" "$OPSBRAIN_VAR" "$OPSBRAIN_VAR/backup-status"
  install -d -m 0700 "$OPSBRAIN_ETC/secrets" "$OPSBRAIN_VAR/backup"

  if [[ -f $OPSBRAIN_ETC/compose.env ]]; then
    OPSBRAIN_HOSTNAME=$(env_get "$OPSBRAIN_ETC/compose.env" OPSBRAIN_HOSTNAME)
    OPSBRAIN_EXTRA_NAMES=$(env_get "$OPSBRAIN_ETC/compose.env" OPSBRAIN_EXTRA_NAMES)
    ok "Keeping existing configuration for $OPSBRAIN_HOSTNAME"
  fi
  local sites name
  sites="$OPSBRAIN_HOSTNAME"
  for name in $OPSBRAIN_EXTRA_NAMES; do sites+=", $name"; done
  write_env_file "$OPSBRAIN_ETC/compose.env" 0644 \
    "# Generated by opsbrainctl. Non-secret deployment settings." \
    "OPSBRAIN_VERSION=$(version)" \
    "OPSBRAIN_ETC=$OPSBRAIN_ETC" \
    "OPSBRAIN_VAR=$OPSBRAIN_VAR" \
    "OPSBRAIN_HOSTNAME=$OPSBRAIN_HOSTNAME" \
    "OPSBRAIN_EXTRA_NAMES=$OPSBRAIN_EXTRA_NAMES" \
    "OPSBRAIN_SITE_ADDRESSES=$sites" \
    "OPSBRAIN_HTTP_PORT=${OPSBRAIN_HTTP_PORT:-80}" \
    "OPSBRAIN_HTTPS_PORT=${OPSBRAIN_HTTPS_PORT:-443}"

  local s=$OPSBRAIN_ETC/secrets
  if [[ ! -f $s/postgres.env ]]; then
    info "Generating secrets (stored in $s, readable by root only)"
    local pg_super pg_owner pg_app valkey key
    pg_super=$(random_secret)
    pg_owner=$(random_secret)
    pg_app=$(random_secret)
    valkey=$(random_secret)
    key=$(random_secret)
    write_env_file "$s/postgres.env" 0600 "POSTGRES_PASSWORD=$pg_super" \
      "OPSBRAIN_DB_OWNER_PASSWORD=$pg_owner" "OPSBRAIN_DB_APP_PASSWORD=$pg_app"
    write_env_file "$s/valkey.env" 0600 "VALKEY_PASSWORD=$valkey"
    write_env_file "$s/app.env" 0600 \
      "OPSBRAIN_DATABASE_URL=postgresql+asyncpg://opsbrain_app:$pg_app@postgres:5432/opsbrain" \
      "OPSBRAIN_REDIS_URL=redis://:$valkey@valkey:6379/0" \
      "OPSBRAIN_SECRET_KEY=$key"
    write_env_file "$s/migrate.env" 0600 \
      "OPSBRAIN_DATABASE_MIGRATION_URL=postgresql+asyncpg://opsbrain_owner:$pg_owner@postgres:5432/opsbrain"
  else
    ok "Keeping existing secrets"
  fi
  if [[ ! -f $s/backup.env ]]; then
    write_env_file "$s/backup.env" 0600 \
      "# Where backups go. Local path, or e.g. s3:https://minio.example:9000/opsbrain-backups" \
      "RESTIC_REPOSITORY=$OPSBRAIN_VAR/backup/restic" \
      "RESTIC_PASSWORD=$(random_secret)" \
      "# For S3/MinIO repositories also set AWS_ACCESS_KEY_ID and AWS_SECRET_ACCESS_KEY." \
      "KEEP_DAILY=7" "KEEP_WEEKLY=4" "KEEP_MONTHLY=6"
    NEW_BACKUP_PASSWORD=1
  fi
}

core_create_admin() {
  local count
  count=$(compose core exec -T api opsbrain-admin user-count 2>/dev/null | tr -d '[:space:]') || count=""
  [[ $count =~ ^[0-9]+$ ]] || die "Could not query the user table; check 'opsbrainctl logs api'."
  if ((count > 0)); then
    ok "Users already exist; skipping first-administrator setup"
    return 0
  fi
  local user=${ADMIN_USER:-} email=${ADMIN_EMAIL:-} pw="" pw2=""
  if [[ -n ${ADMIN_PASSWORD_FILE:-} ]]; then
    [[ -n $user && -n $email ]] || die "--admin-password-file needs --admin-user and --admin-email"
    pw=$(head -n1 "$ADMIN_PASSWORD_FILE")
  else
    [[ -t 0 ]] || die "No terminal to ask for the first administrator. Use --admin-user, --admin-email and --admin-password-file."
    info "Create the first administrator account"
    [[ -n $user ]] || read -r -p "  Username: " user
    [[ -n $email ]] || read -r -p "  Email: " email
    while true; do
      read -r -s -p "  Password (at least 12 characters): " pw
      echo
      read -r -s -p "  Repeat password: " pw2
      echo
      [[ $pw == "$pw2" ]] && break
      warn "Passwords do not match, try again."
    done
  fi
  printf '%s\n' "$pw" | compose core exec -T api opsbrain-admin create-admin --username "$user" --email "$email" ||
    die "Administrator not created (see message above). Re-run: sudo opsbrainctl admin create"
  ok "Administrator '$user' created. Two-factor setup is requested at first sign-in."
}

core_install_cli_and_timers() {
  ln -sfn "$OPSBRAIN_HOME/scripts/opsbrainctl" "$OPSBRAIN_BIN_LINK" 2>/dev/null ||
    warn "Could not link $OPSBRAIN_BIN_LINK"
  if have systemctl && [[ -d /run/systemd/system ]]; then
    local unit
    for unit in opsbrain-backup.service opsbrain-backup.timer opsbrain-cert-renew.service opsbrain-cert-renew.timer; do
      sed "s#@OPSBRAINCTL@#$OPSBRAIN_BIN_LINK#g" "$OPSBRAIN_HOME/deploy/systemd/$unit" >"$OPSBRAIN_SYSTEMD_DIR/$unit"
    done
    systemctl daemon-reload
    systemctl enable --now opsbrain-backup.timer opsbrain-cert-renew.timer >/dev/null
    ok "Scheduled daily backup (02:30) and certificate renewal check"
  else
    warn "systemd not detected: schedule 'opsbrainctl backup --quiet' and 'opsbrainctl cert renew --if-expiring 30' daily yourself."
  fi
}

core_disable_timers() {
  if have systemctl && [[ -d /run/systemd/system ]]; then
    systemctl disable --now opsbrain-backup.timer opsbrain-cert-renew.timer >/dev/null 2>&1 || true
  fi
}

cmd_install_core() {
  require_root install
  if module_installed core; then
    ok "Core is already installed (version $(env_get "$OPSBRAIN_ETC/compose.env" OPSBRAIN_VERSION)). Use 'opsbrainctl upgrade' to update."
    return 0
  fi
  core_preflight
  OPSBRAIN_HOSTNAME=${OPSBRAIN_HOSTNAME:-$(hostname -f 2>/dev/null || hostname)}
  if [[ -z ${OPSBRAIN_EXTRA_NAMES+x} ]]; then
    OPSBRAIN_EXTRA_NAMES=$(hostname -I 2>/dev/null | tr ' ' '\n' | grep -v '^$' | grep -v ':' | tr '\n' ' ' || true)
  fi
  info "Installing AI-OpsBrain core $(version) for https://$OPSBRAIN_HOSTNAME"
  core_write_config
  tls_create_ca
  [[ -s $OPSBRAIN_ETC/tls/server.crt ]] || tls_issue_server

  info "Building images (first run takes a few minutes)"
  compose core build --pull
  info "Starting services"
  compose core up -d --remove-orphans
  wait_healthy core 300 || die "Core did not become healthy. Inspect with: opsbrainctl logs api"
  set_module_installed core
  core_create_admin
  core_install_cli_and_timers

  local url="https://$OPSBRAIN_HOSTNAME"
  [[ ${OPSBRAIN_HTTPS_PORT:-443} == 443 ]] || url+=":$OPSBRAIN_HTTPS_PORT"
  echo
  ok "AI-OpsBrain core is running."
  cat <<EOF

  URL:             $url
  CA certificate:  $OPSBRAIN_ETC/ca/ca.crt  — import it into browsers / OS trust stores (see docs/install-guide.md)
  Status:          sudo opsbrainctl status
  Backups:         daily at 02:30 to $(env_get "$OPSBRAIN_ETC/secrets/backup.env" RESTIC_REPOSITORY)
EOF
  if [[ ${NEW_BACKUP_PASSWORD:-0} == 1 ]]; then
    cat <<EOF

  ${C_YEL}IMPORTANT:${C_OFF} store the backup encryption password somewhere safe and OFF this server.
  Without it, backups cannot be restored after losing this machine:
    sudo grep RESTIC_PASSWORD $OPSBRAIN_ETC/secrets/backup.env
EOF
  fi
}

cmd_upgrade_core() {
  require_root upgrade
  module_installed core || die "Core is not installed."
  check_docker
  if [[ -n ${UPGRADE_REF:-} ]]; then
    have git || die "git is required for --ref"
    [[ -z $(git -C "$OPSBRAIN_HOME" status --porcelain) ]] || die "Local changes in $OPSBRAIN_HOME; commit or stash them first."
    info "Fetching $UPGRADE_REF"
    git -C "$OPSBRAIN_HOME" fetch --tags origin
    git -C "$OPSBRAIN_HOME" checkout --quiet "$UPGRADE_REF"
  fi
  local from to
  from=$(env_get "$OPSBRAIN_ETC/compose.env" OPSBRAIN_VERSION)
  to=$(version)
  info "Upgrading core $from -> $to"
  if [[ ${SKIP_BACKUP:-0} == 1 ]]; then
    confirm "Upgrade WITHOUT a pre-upgrade backup?" || die "Cancelled."
  else
    BACKUP_TAG=pre-upgrade cmd_backup
  fi
  OPSBRAIN_HOSTNAME=$(env_get "$OPSBRAIN_ETC/compose.env" OPSBRAIN_HOSTNAME)
  core_write_config
  compose core build --pull
  compose core up -d --remove-orphans
  if ! wait_healthy core 300; then
    cat >&2 <<EOF
Upgrade did not become healthy. Your data is unchanged in the pre-upgrade backup.
To roll back: check out the previous version ($from) in $OPSBRAIN_HOME, then run
  sudo opsbrainctl restore <pre-upgrade snapshot> && sudo opsbrainctl upgrade
EOF
    exit 1
  fi
  set_module_installed core
  core_install_cli_and_timers
  ok "Core upgraded to $to"
}

cmd_remove_core() {
  require_root remove
  module_installed core || [[ ${PURGE:-0} == 1 ]] || die "Core is not installed."
  local others
  others=$(installed_modules | grep -v '^core$' || true)
  [[ -z $others ]] || die "Remove these modules first: $(echo "$others" | tr '\n' ' ')"
  check_docker
  if [[ ${PURGE:-0} != 1 ]]; then
    confirm "Stop and remove the core containers? Database, configuration, certificates and backups are KEPT." ||
      die "Cancelled."
    compose core down --remove-orphans
    core_disable_timers
    set_module_removed core
    ok "Core removed. Data kept in Docker volumes opsbrain-core_postgres-data / opsbrain-core_valkey-data and $OPSBRAIN_ETC."
    echo "Reinstall with: sudo opsbrainctl install core   (existing data and accounts are reused)"
    return 0
  fi

  cat <<EOF
${C_RED}Full purge of the core module will permanently delete:${C_OFF}
  - Docker volumes opsbrain-core_postgres-data and opsbrain-core_valkey-data (users, roles, audit log, settings)
  - $OPSBRAIN_ETC (configuration, secrets, internal CA and certificates)
Backups in $OPSBRAIN_VAR/backup are kept$([[ ${PURGE_BACKUPS:-0} == 1 ]] && echo " — NO: --purge-backups deletes them too").
EOF
  if [[ ${NO_FINAL_BACKUP:-0} != 1 ]] && compose core ps --status running --services 2>/dev/null | grep -q '^postgres$'; then
    info "Taking a final backup before purging (skip with --no-final-backup)"
    BACKUP_TAG=pre-purge cmd_backup
  fi
  confirm_phrase "purge core" "This cannot be undone."
  compose core down --volumes --remove-orphans
  core_disable_timers
  rm -f "$OPSBRAIN_SYSTEMD_DIR"/opsbrain-backup.* "$OPSBRAIN_SYSTEMD_DIR"/opsbrain-cert-renew.*
  rm -rf "${OPSBRAIN_ETC:?}"
  if [[ ${PURGE_BACKUPS:-0} == 1 ]]; then
    confirm_phrase "delete backups" "Also deleting every backup in $OPSBRAIN_VAR/backup."
    rm -rf "${OPSBRAIN_VAR:?}/backup"
  fi
  [[ -L $OPSBRAIN_BIN_LINK ]] && rm -f "$OPSBRAIN_BIN_LINK"
  ok "Core purged."
}

status_line() {
  local state=$1 label=$2 detail=$3 color
  case "$state" in
    ok) color=$C_GRN ;;
    warning) color=$C_YEL ;;
    *) color=$C_RED ;;
  esac
  printf '  %s%-8s%s %-22s %s\n' "$color" "$state" "$C_OFF" "$label" "$detail"
}

cmd_status() {
  local only=${1:-} rc=0 m
  [[ -f $OPSBRAIN_ETC/compose.env ]] || die "AI-OpsBrain is not installed on this server (no $OPSBRAIN_ETC/compose.env)."
  check_docker
  echo "AI-OpsBrain $(env_get "$OPSBRAIN_ETC/compose.env" OPSBRAIN_VERSION) on https://$(env_get "$OPSBRAIN_ETC/compose.env" OPSBRAIN_HOSTNAME)"
  echo
  echo "Modules:"
  for m in "${ALL_MODULES[@]}"; do
    [[ -n $only && $m != "$only" ]] && continue
    if module_installed "$m"; then
      printf '  %-12s %sinstalled%s\n' "$m" "$C_GRN" "$C_OFF"
    elif in_list "$m" "${AVAILABLE_MODULES[@]}"; then
      printf '  %-12s %snot installed%s\n' "$m" "$C_DIM" "$C_OFF"
    else
      printf '  %-12s %snot available in this release%s\n' "$m" "$C_DIM" "$C_OFF"
    fi
  done
  for m in $(installed_modules); do
    [[ -n $only && $m != "$only" ]] && continue
    echo
    echo "Services ($m):"
    local svc state health
    while read -r svc state health; do
      [[ -z $svc || $svc == migrate ]] && continue
      if [[ $state == running && (-z $health || $health == healthy) ]]; then
        status_line ok "$svc" "${health:-running}"
      else
        status_line critical "$svc" "$state ${health}"
        rc=1
      fi
    done < <(compose "$m" ps -a --format '{{.Service}} {{.State}} {{.Health}}' 2>/dev/null)
    for svc in $(compose "$m" config --services 2>/dev/null); do
      [[ $svc == migrate ]] && continue
      compose "$m" ps -a --format '{{.Service}}' 2>/dev/null | grep -qx "$svc" || {
        status_line critical "$svc" "not created"
        rc=1
      }
    done
  done
  if module_installed core && [[ -z $only || $only == core ]]; then
    echo
    echo "Checks:"
    local days
    days=$(tls_days_left)
    if ((days > 30)); then status_line ok "certificate" "expires in $days days"
    elif ((days > 7)); then status_line warning "certificate" "expires in $days days — run: opsbrainctl cert renew"
    else
      status_line critical "certificate" "expires in $days days — run: opsbrainctl cert renew"
      rc=1
    fi
    local bs=$OPSBRAIN_VAR/backup-status/status.json
    if [[ -f $bs ]]; then
      local result last
      result=$(sed -n 's/.*"last_result": *"\([^"]*\)".*/\1/p' "$bs")
      last=$(sed -n 's/.*"last_success": *"\([^"]*\)".*/\1/p' "$bs")
      if [[ $result == success ]]; then
        local age_h=$((($(date +%s) - $(date -d "$last" +%s)) / 3600))
        if ((age_h <= 26)); then status_line ok "backup" "last success $last"
        else status_line warning "backup" "last success $last (${age_h} h ago)"; fi
      else
        status_line critical "backup" "last backup FAILED: $(sed -n 's/.*"last_error": *"\([^"]*\)".*/\1/p' "$bs")"
        rc=1
      fi
    else
      status_line warning "backup" "no backup yet — run: opsbrainctl backup"
    fi
    local ready
    ready=$(compose core exec -T web wget -q -O - --header "Host: $(env_get "$OPSBRAIN_ETC/compose.env" OPSBRAIN_HOSTNAME)" \
      --no-check-certificate https://127.0.0.1/api/health/ready 2>/dev/null || true)
    if [[ $ready == *'"ok"'* ]]; then status_line ok "https endpoint" "API ready through the TLS proxy"
    else
      status_line critical "https endpoint" "API not reachable through the TLS proxy"
      rc=1
    fi
    local disk
    disk=$(df -P "$(docker info --format '{{.DockerRootDir}}' 2>/dev/null || echo /)" | awk 'NR==2 {print $5}' | tr -d '%')
    if ((disk < 80)); then status_line ok "disk" "${disk}% used (Docker data)"
    elif ((disk < 90)); then status_line warning "disk" "${disk}% used (Docker data)"
    else
      status_line critical "disk" "${disk}% used (Docker data)"
      rc=1
    fi
  fi
  return $rc
}
